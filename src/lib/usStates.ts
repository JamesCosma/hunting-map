/**
 * Resolves "NV", "nv" or "Nevada" to the full state name, or null if the text
 * is not a recognizable US state.
 */
export function resolveStateName(text: string): string | null {
  const trimmed = text.trim();
  if (trimmed === '') return null;
  const byAbbreviation = US_STATES[trimmed.toUpperCase()];
  if (byAbbreviation) return byAbbreviation;
  const lower = trimmed.toLowerCase();
  return Object.values(US_STATES).find((name) => name.toLowerCase() === lower) ?? null;
}
