/**
 * Regenerates src/data/synopticNetworks.ts from Synoptic's /v2/networks list.
 *
 * The table maps each network id to its short name and category so the app
 * can label station types without spending an API request per visit.
 * Run when Synoptic adds networks (unknown ids fall back to "Mesonet"):
 *
 *   SYNOPTIC_TOKEN=... node scripts/generate-synoptic-networks.mjs
 *
 * The token is read from the environment and never written anywhere.
 */
import { writeFile } from 'node:fs/promises';

const token = (process.env.SYNOPTIC_TOKEN ?? process.env.VITE_SYNOPTIC_TOKEN ?? '').trim();
if (token === '') {
  console.error('Set SYNOPTIC_TOKEN (or VITE_SYNOPTIC_TOKEN) to a Synoptic public token.');
  process.exit(1);
}

const url = new URL('https://api.synopticdata.com/v2/networks');
url.searchParams.set('token', token);
const response = await fetch(url);
if (!response.ok) {
  console.error(`Synoptic responded with ${response.status}`);
  process.exit(1);
}
const json = await response.json();
const networks = (json.MNET ?? [])
  .map((network) => ({
    id: String(network.ID),
    name: String(network.SHORTNAME ?? network.ID).trim(),
    category: Number(network.CATEGORY ?? 0) || 0,
  }))
  .sort((a, b) => Number(a.id) - Number(b.id));

if (networks.length === 0) {
  console.error('Synoptic returned no networks; leaving the table unchanged.');
  process.exit(1);
}

const lines = networks.map(
  ({ id, name, category }) =>
    `  '${id}': [${JSON.stringify(name).replaceAll("'", "\\'")}, ${category}],`,
);
const source = `// Generated by scripts/generate-synoptic-networks.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Synoptic network id -> [short name, category id from /v2/networktypes].

export const SYNOPTIC_NETWORKS: Readonly<Record<string, readonly [name: string, category: number]>> = {
${lines.join('\n')}
};
`;
await writeFile(new URL('../src/data/synopticNetworks.ts', import.meta.url), source);
console.warn(`Wrote ${networks.length} networks.`);
